const FALLBACK_RESPONSE = (ctx: CoachContext) =>
  `Я рядом, ${ctx.firstName}. Расскажи чуть подробнее, что происходит — с питанием, тренировкой или программой в целом — и я подскажу конкретный следующий шаг, с учётом того, что сегодня День ${ctx.dayNumber}.`;

export function getMockCoachResponse(userMessage: string, ctx: CoachContext): string {
  const lower = userMessage.toLowerCase();
  const rule = MOCK_RULES.find((r) => r.keywords.some((k) => lower.includes(k)));
  return rule ? rule.response(ctx) : FALLBACK_RESPONSE(ctx);
}

// --- Real implementation (OpenAI-compatible) -------------------------------
// Swapped in automatically by app/api/ai/route.ts when AI_API_KEY is set.

export function buildPersonalizedPrompt(ctx: CoachContext, userMessage: string): string {
  return [
    `Профиль: День ${ctx.dayNumber} из 56 (неделя ${ctx.weekNumber}). Цель: ${ctx.goal}.`,
    ctx.knownDifficulties.length ? `Известные сложности: ${ctx.knownDifficulties.join(", ")}.` : "",
    `Питание сегодня: ${ctx.todayNutritionDone ? "отмечено выполненным" : "ещё не отмечено"}. Тренировка сегодня: ${
      ctx.todayWorkoutDone ? "выполнена" : "ещё не выполнена"
    }.`,
    `Сообщение пользователя: "${userMessage}"`,
  ]
    .filter(Boolean)
    .join("\n");
}

export async function getRealCoachResponse(userMessage: string, ctx: CoachContext, apiKey: string): Promise<string> {
  const res = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model: "gpt-4o-mini",
      messages: [
        { role: "system", content: AI_COACH_SYSTEM_PROMPT },
        { role: "user", content: buildPersonalizedPrompt(ctx, userMessage) },
      ],
      max_tokens: 400,
      temperature: 0.6,
    }),
  });

  if (!res.ok) throw new Error(`AI provider error: ${res.status}`);
  const data = await res.json();
  return data.choices?.[0]?.message?.content ?? FALLBACK_RESPONSE(ctx);
}

